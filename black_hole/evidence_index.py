@dataclass(frozen=True)
class Source:
    """Where one manuscript artifact comes from."""

    package: str
    command: str
    artifact: str | None = None
    note: str = ""
    supplied: bool = False


@dataclass
class Entry:
    kind: str
    name: str
    source: Source
    manifest_path: str | None = None
    sha256: str | None = None
    issues: list[str] = field(default_factory=list)


