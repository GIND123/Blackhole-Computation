def _load_manifest(package: str, root: Path) -> dict:
    path = root / package / "manifest.json"
    if not path.exists():
        return {}
    manifest = json.loads(path.read_text(encoding="utf-8"))
    lookup = {}
    for section in ("archives", "derived_artifacts"):
        for row in manifest.get(section, []):
            lookup[row["path"]] = row
    return {
        "rows": lookup,
        "simulation_commits": manifest.get("simulation_commits", []),
        "analysis_commit": manifest.get("analysis_commit"),
        "grades": sorted(
            {
                row.get("provenance_grade", "unrecorded")
                for row in manifest.get("archives", [])
            }
        ),
    }


def _cited(manuscript: Path) -> tuple[list[str], list[str]]:
    text = manuscript.read_text(encoding="utf-8")
    figures = [Path(match).name for match in GRAPHIC.findall(text)]
    tables = LABEL.findall(text)
    return figures, tables


def build(root: Path = Path(".")) -> dict:
    """Return the index and every inconsistency found while building it."""

    root = root.resolve()
    manuscript = root / MANUSCRIPT
    figures, tables = _cited(manuscript)
    manifests = {
        package: _load_manifest(package, root)
        for package in (REGULATOR_PACKAGE, TAIL_PACKAGE)
    }

    entries: list[Entry] = []
    problems: list[str] = []

    def record(kind: str, name: str, source: Source) -> None:
        entry = Entry(kind=kind, name=name, source=source)
        if source.artifact:
            artifact = root / source.artifact
            if not artifact.exists():
                entry.issues.append("artifact missing from the repository")
            manifest = manifests.get(source.package) or {}
            row = (manifest.get("rows") or {}).get(source.artifact)
            if row is None:
                entry.issues.append("artifact not recorded in the package manifest")
            else:
                entry.manifest_path = source.artifact
                entry.sha256 = row["sha256"]
        entries.append(entry)
        for issue in entry.issues:
            problems.append(f"{kind} {name}: {issue}")

    for name in figures:
        source = FIGURES.get(name)
        if source is None:
            problems.append(f"figure {name}: cited by the manuscript but not indexed")
            continue
        record("figure", name, source)
    for name in tables:
        source = TABLES.get(name)
        if source is None:
            problems.append(f"table {name}: labelled in the manuscript but not indexed")
            continue
        record("table", name, source)
    for name, source in PENDING.items():
        record("pending", name, source)

    for name in FIGURES:
        if name not in figures:
            problems.append(f"figure {name}: indexed but not cited by the manuscript")
    for name in TABLES:
        if name not in tables:
            problems.append(f"table {name}: indexed but not labelled in the manuscript")

    return {
        "manuscript": MANUSCRIPT.as_posix(),
        "entries": [
            {
                "kind": entry.kind,
                "name": entry.name,
                "package": entry.source.package,
                "artifact": entry.source.artifact,
                "command": entry.source.command,
                "note": entry.source.note,
                "sha256": entry.sha256,
                "issues": entry.issues,
            }
            for entry in entries
        ],
        "packages": {
            package: {
                "analysis_commit": (manifests[package] or {}).get("analysis_commit"),
                "simulation_commits": (manifests[package] or {}).get(
                    "simulation_commits", []
                ),
                "provenance_grades": (manifests[package] or {}).get("grades", []),
            }
            for package in manifests
        },
        "problems": problems,
    }


def render(index: dict) -> str:
    """Return the index as a document."""

    lines = [
        "# Evidence index",
        "",
        "Every figure and numbered table in "
        f"[`{index['manuscript']}`](../{index['manuscript']}) with the artifact "
        "it draws, the command that regenerates that artifact, and the package "
        "manifest entry that fixes its hash.",
        "",
        "This file is generated by `python -m black_hole.evidence_index`. It is "
        "not edited by hand, and a disagreement with the repository is reported "
        "as a problem rather than silently absorbed.",
        "",
        "## Packages",
        "",
        "| package | analysis commit | simulation commits | provenance |",
        "|---|---|---|---|",
    ]
    for package, record in index["packages"].items():
        commits = ", ".join(
            f"`{value[:12]}`" for value in record.get("simulation_commits", [])
        ) or "n/a"
        analysis = record.get("analysis_commit")
        lines.append(
            f"| `{package}` | `{(analysis or 'n/a')[:12]}` | {commits} | "
            f"{', '.join(record.get('provenance_grades') or ['n/a'])} |"
        )

    for kind, title, blurb in (
        ("figure", "Figures in the manuscript", ""),
        ("table", "Tables in the manuscript", ""),
        (
            "pending",
            "Assembled but not yet cited",
            "These results exist and are verified, and are intended for the "
            "manuscript once their placement is settled.",
        ),
    ):
        rows = [entry for entry in index["entries"] if entry["kind"] == kind]
        if not rows:
            continue
        lines += ["", f"## {title}", ""]
        if blurb:
            lines += [blurb, ""]
        lines += [
            "| name | artifact | regenerate with | sha256 |",
            "|---|---|---|---|",
        ]
        for entry in rows:
            digest = f"`{entry['sha256'][:12]}`" if entry["sha256"] else "not recorded"
            artifact = f"`{entry['artifact']}`" if entry["artifact"] else entry["note"]
            lines.append(
                f"| `{entry['name']}` | {artifact} | `{entry['command']}` | {digest} |"
            )

    problems = index["problems"]
    lines += ["", "## Consistency", ""]
    if problems:
        lines.append(
            f"{len(problems)} item(s) need attention:"
        )
        lines.append("")
        lines += [f"* {problem}" for problem in problems]
    else:
        lines.append(
            "Every cited figure and table is indexed, present, and recorded in "
            "its package manifest."
        )
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--check", action="store_true",
                        help="exit non zero when the index finds a problem")
    arguments = parser.parse_args()
    index = build(arguments.root)
    (arguments.root / OUTPUT).write_text(render(index), encoding="utf-8")
    (arguments.root / RECORD).write_text(
        json.dumps(index, indent=2), encoding="utf-8"
    )
    print(f"{OUTPUT} written with {len(index['entries'])} entries")
    for problem in index["problems"]:
        print("  problem:", problem)
    if arguments.check and index["problems"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
